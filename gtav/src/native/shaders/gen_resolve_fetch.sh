#!/bin/sh
# Regenerates native_resolve_fetch_shaders.h (no dxc on the Mac; glslangValidator from Homebrew).
set -e
cd "$(dirname "$0")"
G=${GLSLANG:-glslangValidator}
T=$(mktemp -d)
out=native_resolve_fetch_shaders.h
echo "// Generated by gen_resolve_fetch.sh from native_resolve_fetch.{vert,frag} and native_resolve_compute.comp." > $out
echo "#pragma once" >> $out
$G -V --target-env vulkan1.2 --vn g_native_resolve_fetch_vs -o $T/vs.h native_resolve_fetch.vert >/dev/null
cat $T/vs.h >> $out
for i in 0 1 2 3; do
  $G -V --target-env vulkan1.2 -DSOURCE=$i --vn g_native_resolve_fetch_ps$i -o $T/ps.h native_resolve_fetch.frag >/dev/null
  cat $T/ps.h >> $out
done
$G -V --target-env vulkan1.2 --vn g_native_resolve_compute_cs -o $T/cs.h native_resolve_compute.comp >/dev/null
cat $T/cs.h >> $out
$G -V --target-env vulkan1.2 --vn g_native_clear_ps -o $T/clear.h native_clear.frag >/dev/null
cat $T/clear.h >> $out
rm -rf "$T"
